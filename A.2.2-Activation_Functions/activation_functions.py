# Plot custom activation function
x = np.linspace(-40, 40, 8000)
plt.figure(figsize=(8, 8))
plt.plot(x, -0.9 / (1 + np.exp(x / 5)) + 0.8 / (1 + np.exp(-x / 5)), label="custom", color='b')
#plt.title("Activation Function")
#plt.xlabel("Input")
#plt.ylabel("Output")
plt.yticks(np.arange(-0.9, 0.85, 0.1))
plt.grid(True)
plt.axhline(0, color='black', linewidth=1)
plt.axvline(0, color='black', linewidth=1)
plt.legend()
#plt.show()
pylab.savefig('B-custom_activation.png')
pylab.clf()
